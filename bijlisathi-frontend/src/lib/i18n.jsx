const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => {
    try { return localStorage.getItem('bs_lang') || 'en'; } catch (e) { return 'en'; }
  });
  useEffect(() => { try { localStorage.setItem('bs_lang', lang); document.documentElement.lang = lang; } catch (e) {} }, [lang]);
  const t = (k) => dict[lang]?.[k] ?? dict.en[k] ?? k;
  const toggle = () => setLang((l) => (l === 'en' ? 'hi' : 'en'));
  return <LanguageContext.Provider value={{ lang, t, toggle, setLang }}>{children}</LanguageContext.Provider>;
}

export function useLang() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLang must be used within LanguageProvider');
  return ctx;
}

